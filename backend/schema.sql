CREATE TABLE IF NOT EXISTS public.mixology (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    brand text NOT NULL,
    name text NOT NULL,
    description text,
    tags text,
    flavor_intensity integer CHECK (flavor_intensity BETWEEN 1 AND 10),
    flavor_profile jsonb,
    aromatic_notes jsonb,
    dominant_flavor text,
    temporal_dynamics text,
    strength text,
    seasonality text,
    cultural_associations text,
    flavor_type text,
    UNIQUE (brand, name)
);
